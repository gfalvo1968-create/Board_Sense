"""Draft-only Board Sense -> membership service client (NOT wired to analysis routes).

Purpose:
- A verified customer bearer token can be forwarded to the membership backend,
  which MUST authenticate it using the customer Auth provider itself.
- A separate server-side service credential authenticates Board Sense to the
  membership backend. Never put this credential in a public webpage.
- The membership backend, never the browser or Board Sense, decides plan and
  allowance from its provider-reconciled production ledger.

Security: disabled by default, exact HTTPS origin allowlist, no HTTP redirect
following, no client-controlled destinations, identity, plan or quota arguments.
No fallback to anonymous access when member verification fails.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date
import json
import os
import re
from urllib.error import HTTPError, URLError
from urllib.parse import urlsplit
from urllib.request import Request, HTTPRedirectHandler, build_opener
from uuid import UUID

SERVICE_KEY_HEADER = "X-SRF-Board-Service-Key"
ALLOWED_ORIGINS = frozenset({
    "https://scrapradar-backend-production.up.railway.app",
})
RESERVATION_PATH = "/api/internal/board/cases/reserve"
TOKEN_RE = re.compile(r"^[A-Za-z0-9_.~\-]{20,8192}$")


class MembershipBridgeError(Exception):
    """No member analysis may proceed after any of these errors."""


class MembershipBridgeDisabled(MembershipBridgeError):
    pass


class MembershipBridgeDenied(MembershipBridgeError):
    """Member is authenticated but is not allowed another paid case."""


class MembershipBridgeUnavailable(MembershipBridgeError):
    """Request cannot be reconciled safely; never turn this into a free scan."""


@dataclass(frozen=True)
class PaidCaseReservation:
    case_id: str
    used_today: int
    remaining: int
    day_utc: str
    limit: int = 25


class _NoRedirect(HTTPRedirectHandler):
    """Bearer tokens and service keys must never follow a redirect."""
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def _trusted_origin() -> str:
    origin = os.getenv("SCRAP_RADAR_MEMBERSHIP_ORIGIN", "").strip()
    # Exact equality prevents URL confusion, alternate ports, HTTP downgrade,
    # and leaking credentials to a configurable arbitrary remote destination.
    parts = urlsplit(origin)
    if (origin not in ALLOWED_ORIGINS or parts.scheme != "https"
            or parts.netloc != parts.hostname or parts.path or parts.query
            or parts.fragment or parts.username or parts.password):
        raise MembershipBridgeUnavailable("Membership service origin is not approved")
    return origin


def _bearer_token(header: str | None) -> str:
    if not isinstance(header, str) or not header.startswith("Bearer "):
        raise MembershipBridgeDenied("Sign in to use paid board analysis")
    token = header[7:]
    if not TOKEN_RE.fullmatch(token):
        raise MembershipBridgeDenied("Invalid customer authentication")
    return token


def reserve_paid_case(auth_header: str | None, case_id: str) -> PaidCaseReservation:
    """Reserve one case after upload validation, before any board analysis.

    Only future trusted server-side integration should call this routine.
    The case UUID is generated by Board Sense, not supplied by the browser.
    This module deliberately exports no HTTP endpoint.
    """
    if os.getenv("BOARD_SENSE_MEMBER_BRIDGE_ENABLED", "") != "1":
        raise MembershipBridgeDisabled("Paid board analysis has not been enabled")
    token = _bearer_token(auth_header)
    try:
        case_id = str(UUID(case_id))
    except (TypeError, ValueError, AttributeError):
        raise MembershipBridgeDenied("Invalid server-generated case identifier") from None
    secret = os.getenv("SCRAP_RADAR_BOARD_SERVICE_KEY", "")
    if len(secret) < 32 or any(c.isspace() for c in secret):
        raise MembershipBridgeUnavailable("Membership service authentication is not configured")
    origin = _trusted_origin()
    body = json.dumps({"case_id": case_id}, separators=(",", ":")).encode("utf-8")
    req = Request(
        origin + RESERVATION_PATH,
        data=body, method="POST",
        headers={
            "Authorization": "Bearer " + token,
            SERVICE_KEY_HEADER: secret,
            "Content-Type": "application/json",
            "Accept": "application/json",
        },
    )
    try:
        # Explicitly no redirects: do not leak a bearer token or service key
        # to an attacker-controlled host through a 301/302/307/308.
        with build_opener(_NoRedirect()).open(req, timeout=6) as response:
            if response.status != 200:
                raise MembershipBridgeUnavailable("Membership service returned an unexpected status")
            payload = json.load(response)
    except HTTPError as error:
        if error.code in (401, 403, 429):
            raise MembershipBridgeDenied("Membership or daily allowance not available") from None
        raise MembershipBridgeUnavailable("Membership service could not verify usage") from None
    except (URLError, TimeoutError, OSError, ValueError, TypeError, UnicodeDecodeError):
        raise MembershipBridgeUnavailable("Membership service could not verify usage") from None

    if not isinstance(payload, dict) or payload.get("allowed") is not True:
        raise MembershipBridgeDenied("Membership service did not authorize the case")
    # Strong response validation protects against a malformed/untrusted reply.
    usage = payload.get("usage")
    if not isinstance(usage, dict) or payload.get("case_id") != case_id:
        raise MembershipBridgeUnavailable("Membership service response is invalid")
    used, remaining, limit, day = (
        usage.get("used_today"), usage.get("remaining"),
        usage.get("limit"), usage.get("day_utc"),
    )
    if (type(used) is not int or type(remaining) is not int
            or type(limit) is not int or limit != 25
            or not 1 <= used <= limit or remaining != limit - used
            or not isinstance(day, str)):
        raise MembershipBridgeUnavailable("Membership allowance response is invalid")
    try:
        if date.fromisoformat(day).isoformat() != day:
            raise ValueError()
    except ValueError:
        raise MembershipBridgeUnavailable("Membership allowance date is invalid") from None
    return PaidCaseReservation(case_id, used, remaining, day, limit)
